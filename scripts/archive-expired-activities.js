/* global process */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputSql = join(root, 'supabase', 'seed', 'activity_expired_listing_archives.generated.sql');
const outputAudit = join(root, 'data', 'activity_expired_listing_archives.generated.json');

// Do not archive a source merely because a scrape changed or failed. A listing
// is hidden only when its own structured availability proves it has ended.
const sql = `-- Generated by scripts/archive-expired-activities.js
-- Archive only records with an explicit end date in the past. Historical rows
-- remain in PostgreSQL and can be restored if their source publishes new dates.

with expired as (
  select activity_id
  from public.activities
  where public_listing_status = 'published'
    and (
      activity_date < current_date
      or availability_end_date < current_date
      or (
        availability_type in ('one_off', 'specific_dates')
        and coalesce((select max(day) from unnest(available_dates) as day), activity_date) < current_date
      )
    )
)
update public.activities as activity
set public_listing_status = 'archived', updated_at = now()
from expired
where activity.activity_id = expired.activity_id;
`;

mkdirSync(dirname(outputSql), { recursive: true });
mkdirSync(dirname(outputAudit), { recursive: true });
writeFileSync(outputSql, sql);
writeFileSync(outputAudit, JSON.stringify({
  generated_at: new Date().toISOString(),
  policy: 'Only explicit past activity dates, availability end dates, or fully elapsed specific date lists are archived.',
}, null, 2) + '\n');
console.log('Generated conservative expired-listing archive SQL.');
