/*
 * The council search feed shows a finite set of next occurrences, while many
 * individual event pages say the session runs every week. Upgrade only pages
 * with that explicit wording so future planning weeks do not go empty.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputSql = join(root, 'supabase', 'seed', 'activity_better_start_recurring_availability.generated.sql');
const outputAudit = join(root, 'data', 'better_start_recurring_availability.generated.json');

function envFile() {
  return join(root, '.env.local');
}

async function loadEnv() {
  const { readFile } = await import('node:fs/promises');
  const content = await readFile(envFile(), 'utf8');
  return Object.fromEntries(content.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^\s*([^=\s]+)\s*=\s*(.*?)\s*$/);
    return match ? [[match[1], match[2].replace(/^['"]|['"]$/g, '')]] : [];
  }));
}

function sql(value) {
  return `$$${String(value).replaceAll('$$', '$ $')}$$`;
}

function cleanText(value) {
  return String(value || '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

async function fetchActivities(env) {
  const rows = [];
  for (let offset = 0; ; offset += 1000) {
    const url = new URL('/rest/v1/activities', env.VITE_SUPABASE_URL);
    url.searchParams.set('select', 'activity_id,activity_name,source_url,available_days_of_week,availability_notes,availability_type');
    url.searchParams.set('source_name', 'eq.Waltham Forest Best Start in Life events');
    url.searchParams.set('public_listing_status', 'eq.published');
    url.searchParams.set('limit', '1000');
    url.searchParams.set('offset', String(offset));
    const response = await fetch(url, {
      headers: { apikey: env.VITE_SUPABASE_ANON_KEY, Authorization: `Bearer ${env.VITE_SUPABASE_ANON_KEY}` },
    });
    if (!response.ok) throw new Error(`Supabase returned ${response.status}`);
    const batch = await response.json();
    rows.push(...batch);
    if (batch.length < 1000) return rows;
  }
}

async function fetchPage(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'TinyOutings/1.0 (+https://tiny-outings-cpjh.onrender.com)' },
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`Council page returned ${response.status}`);
  return cleanText(await response.text());
}

async function mapWithConcurrency(values, limit, mapper) {
  const results = [];
  let next = 0;
  async function worker() {
    while (next < values.length) {
      const index = next;
      next += 1;
      results[index] = await mapper(values[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, values.length) }, worker));
  return results;
}

const env = await loadEnv();
const activities = await fetchActivities(env);
const audit = await mapWithConcurrency(activities, 5, async (activity) => {
  try {
    const text = await fetchPage(activity.source_url);
    const recurring = /\bevery\s+(monday|tuesday|wednesday|thursday|friday|saturday|sunday)\b|\bweekly\b/i.test(text);
    return { activity, recurring, status: 'checked' };
  } catch (error) {
    return { activity, recurring: false, status: 'error', error: error.message };
  }
});
const updates = audit.filter((item) => item.recurring).map((item) => item.activity);
const sqlBody = updates.length
  ? `with recurring_rows (activity_id) as (\n  values\n    ${updates.map((item) => `(${sql(item.activity_id)}::uuid)`).join(',\n    ')}\n)\nupdate public.activities activity\nset\n  availability_type = 'weekly',\n  availability_notes = concat_ws(' ', regexp_replace(coalesce(activity.availability_notes, ''), '^Council dates listed through [0-9-]+\\.\\s*', ''), 'The council event page states this session runs weekly.'),\n  updated_at = now()\nfrom recurring_rows rows\nwhere activity.activity_id = rows.activity_id;\n`
  : '-- No explicitly recurring Better Start rows found.\n';

mkdirSync(dirname(outputSql), { recursive: true });
mkdirSync(dirname(outputAudit), { recursive: true });
writeFileSync(outputSql, `-- Generated by refresh-better-start-recurring-availability.js\n${sqlBody}`);
writeFileSync(outputAudit, `${JSON.stringify({
  generated_at: new Date().toISOString(),
  checked: audit.length,
  recurring_updates: updates.length,
  errors: audit.filter((item) => item.status === 'error').map((item) => ({ activity_name: item.activity.activity_name, error: item.error })),
}, null, 2)}\n`);
console.log(`Checked ${audit.length} Better Start listings; ${updates.length} explicitly recurring listings will remain weekly.`);
