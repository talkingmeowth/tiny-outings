import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputSql = join(root, 'supabase', 'seed', 'activity_import_quality_updates.generated.sql');
const outputAudit = join(root, 'data', 'activity_import_quality_updates.generated.json');

// This is intentionally database-side: every importer, including older ones,
// receives the same safe clean-up before records become visible in the app.
const sql = `-- Generated by scripts/apply-activity-data-quality.js
-- Shared non-destructive quality rules for all Tiny Outings importers.

update public.activities
set
  activity_name = nullif(regexp_replace(trim(activity_name), '[[:cntrl:]]+', ' ', 'g'), ''),
  address = nullif(regexp_replace(trim(address), '[[:cntrl:]]+', ' ', 'g'), ''),
  description = nullif(regexp_replace(trim(description), '[[:cntrl:]]+', ' ', 'g'), ''),
  cost = nullif(regexp_replace(trim(cost), '[[:cntrl:]]+', ' ', 'g'), ''),
  website = nullif(trim(website), ''),
  organiser_website = nullif(trim(organiser_website), ''),
  source_url = nullif(trim(source_url), ''),
  image_url = nullif(trim(image_url), ''),
  updated_at = now()
where activity_name ~ '[[:cntrl:]]'
   or address ~ '[[:cntrl:]]'
   or description ~ '[[:cntrl:]]'
   or cost ~ '[[:cntrl:] ]$'
   or website ~ '^\\s+$'
   or organiser_website ~ '^\\s+$'
   or source_url ~ '^\\s+$'
   or image_url ~ '^\\s+$';

-- Restore source grouping from the stable importer provenance. This keeps the
-- Plan filter and card tag consistent even when a legacy importer used "other".
update public.activities
set data_source = case
  when source_name = 'Happity' then 'Happity'
  when source_name ilike 'Google Places%' then 'Google Places'
  when source_name ilike 'Better Start%' then 'Better Start for Life'
  when source_name ilike 'Eventbrite%' then 'Eventbrite'
  when source_name ilike 'Fever%' then 'Fever'
  when source_name ilike 'Loopla%' then 'Loopla'
  when source_name ilike 'Time Out%' then 'Time Out'
  when source_name ilike 'Museums London%' then 'Museums London'
  when source_name ilike '%directory%' then 'Local directory'
  else coalesce(nullif(data_source, ''), 'Other')
end,
updated_at = now()
where source_name is not null;
`;

mkdirSync(dirname(outputSql), { recursive: true });
mkdirSync(dirname(outputAudit), { recursive: true });
writeFileSync(outputSql, sql);
writeFileSync(outputAudit, JSON.stringify({
  generated_at: new Date().toISOString(),
  rules: ['trim whitespace and control characters', 'restore data_source from source_name'],
}, null, 2) + '\n');
console.log('Generated shared activity data-quality SQL.');
