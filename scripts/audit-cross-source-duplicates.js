/*
 * Conservative, repeatable dedupe for the Tiny Outings update job.
 * Archives only exact same activity/venue/schedule imports; never widens a
 * keeper's dates or times, and leaves all history attached to the old row.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { loadActiveActivities } from './lib/active-activity-reader.js';
import { findExactDuplicateGroups } from './lib/activity-dedupe.js';

const root = process.cwd();
const auditPath = path.join(root, 'data', 'cross_source_duplicate_audit.generated.json');
const sqlPath = path.join(root, 'supabase', 'seed', 'activity_cross_source_duplicate_consolidation.generated.sql');
const columns = [
  'activity_id', 'activity_name', 'address', 'category', 'postcode', 'public_listing_status',
  'data_source', 'source_name', 'source_url', 'website', 'google_place_id',
  'activity_date', 'available_dates', 'days_of_week', 'available_days_of_week',
  'start_time', 'end_time', 'time_window', 'availability_type',
  'availability_start_date', 'availability_end_date', 'created_at', 'updated_at',
  'description', 'admin_cover_image_url', 'reviewed_image_url', 'reviewed_image_selected_at',
  'user_image_url', 'use_category_image', 'image_review_approved_at',
];

function parseEnv(contents) {
  return Object.fromEntries(contents.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^\s*([A-Z0-9_]+)=(.*)\s*$/);
    return match ? [[match[1], match[2].replace(/^['"]|['"]$/g, '')]] : [];
  }));
}

function sql(value) { return `'${String(value).replaceAll("'", "''")}'`; }

function archiveStatement(keeper, duplicate) {
  const reason = `Duplicate of ${keeper.activity_id}: same activity, venue and session`;
  const dependentTables = [
    'activity_reviews', 'comments_table', 'activity_photos', 'activity_swipes',
    'activity_shortlist', 'activity_user_statuses', 'calendar_events',
    'activity_image_manual_reviews', 'activity_curation_feedback',
  ];
  const noHistory = dependentTables.map((table) =>
    `not exists (select 1 from public.${table} history where history.activity_id = activity.activity_id)`).join('\n  and ');
  return `update public.activities activity
set archive = true,
    public_listing_status = 'archived',
    archive_reason = ${sql(reason)},
    archived_at = coalesce(archived_at, now()),
    updated_at = now()
where activity.activity_id = ${sql(duplicate.activity_id)}::uuid
  and activity.updated_at = ${sql(duplicate.updated_at)}::timestamptz
  and activity.archive = false
  and activity.public_listing_status in ('draft', 'published')
  and activity.admin_cover_image_url is null
  and activity.reviewed_image_url is null
  and activity.reviewed_image_selected_at is null
  and activity.user_image_url is null
  and activity.use_category_image is not true
  and activity.image_review_approved_at is null
  and ${noHistory}
  and exists (
    select 1 from public.activities keeper
    where keeper.activity_id = ${sql(keeper.activity_id)}::uuid
      and keeper.archive = false
      and keeper.public_listing_status in ('draft', 'published')
      and keeper.updated_at = ${sql(keeper.updated_at)}::timestamptz
  );`;
}

const env = { ...process.env, ...parseEnv(await fs.readFile(path.join(root, '.env.local'), 'utf8')) };
if (!env.VITE_SUPABASE_URL || !(env.VITE_SUPABASE_SERVICE_ROLE_KEY || env.SUPABASE_SERVICE_ROLE_KEY || await fs.stat(path.join(root, 'supabase', '.temp', 'project-ref')).then(() => true).catch(() => false))) {
  throw new Error('A linked database or service-role key is required to audit both published and draft listings.');
}
const activities = await loadActiveActivities({
  root,
  supabaseUrl: env.VITE_SUPABASE_URL,
  supabaseAnonKey: env.VITE_SUPABASE_ANON_KEY,
  supabaseServiceRoleKey: env.VITE_SUPABASE_SERVICE_ROLE_KEY || env.SUPABASE_SERVICE_ROLE_KEY,
  columns,
  requireComplete: true,
});
const { groups, excluded } = findExactDuplicateGroups(activities);
const audit = {
  audited_at: new Date().toISOString(),
  active_listings: activities.length,
  groups: groups.map(({ keeper, duplicates }) => ({
    keeper: { activity_id: keeper.activity_id, activity_name: keeper.activity_name, address: keeper.address,
      status: keeper.public_listing_status, source_url: keeper.source_url },
    duplicates: duplicates.map((item) => ({ activity_id: item.activity_id, activity_name: item.activity_name,
      address: item.address, status: item.public_listing_status, source_url: item.source_url })),
  })),
  excluded: excluded.map(({ reason, activities: members }) => ({ reason,
    members: members.map((item) => ({ activity_id: item.activity_id, activity_name: item.activity_name, address: item.address })) })),
};
const statements = groups.flatMap(({ keeper, duplicates }) => duplicates.map((duplicate) => archiveStatement(keeper, duplicate)));
const generatedSql = `-- Generated by scripts/audit-cross-source-duplicates.js
-- ${activities.length} active records audited; ${groups.length} exact duplicate groups; ${statements.length} proposed archives.
-- Existing reviews and plans remain attached to archived records. No dates or times are merged.
begin;
${statements.join('\n\n') || '-- No safe duplicates found.'}
commit;
`;
await fs.writeFile(auditPath, `${JSON.stringify(audit, null, 2)}\n`);
await fs.writeFile(sqlPath, generatedSql);
console.log(`Audited ${activities.length} active listings. Found ${groups.length} safe duplicate groups (${statements.length} redundant records); ${excluded.length} ambiguous groups excluded.`);
