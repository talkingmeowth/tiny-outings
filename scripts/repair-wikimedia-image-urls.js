/*
 * Refreshes stored Wikimedia image URLs from the Commons API. The API chooses
 * the valid responsive thumbnail path, so we never guess a width from a URL.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const ROOT = process.cwd();
const OUTPUT_PATH = path.join(ROOT, 'supabase', 'seed', 'activity_wikimedia_image_url_repairs.generated.sql');
const COMMONS_API = 'https://commons.wikimedia.org/w/api.php';
const DELAY_MS = 500;

function parseEnv(contents) {
  return Object.fromEntries(contents.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^\s*([A-Z0-9_]+)=(.*)\s*$/);
    return match ? [[match[1], match[2].replace(/^['"]|['"]$/g, '')]] : [];
  }));
}

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function filenameFromUrl(imageUrl) {
  const url = new URL(imageUrl);
  const parts = url.pathname.split('/').filter(Boolean);
  const thumbIndex = parts.indexOf('thumb');
  const filename = thumbIndex >= 0 ? parts.at(-2) : parts.at(-1);
  return filename ? decodeURIComponent(filename) : null;
}

async function getActivities(env) {
  const rows = [];
  for (let offset = 0; ; offset += 1000) {
    const url = new URL('/rest/v1/activities', env.VITE_SUPABASE_URL);
    url.searchParams.set('select', 'activity_id,wikimedia_image_url');
    url.searchParams.set('wikimedia_image_url', 'not.is.null');
    url.searchParams.set('order', 'activity_id.asc');
    url.searchParams.set('limit', '1000');
    url.searchParams.set('offset', String(offset));
    const response = await fetch(url, { headers: { apikey: env.VITE_SUPABASE_ANON_KEY, Authorization: `Bearer ${env.VITE_SUPABASE_ANON_KEY}` } });
    if (!response.ok) throw new Error(`Supabase activity fetch failed: ${response.status}`);
    const batch = await response.json();
    rows.push(...batch);
    if (batch.length < 1000) return rows;
  }
}

async function validThumbnailUrl(imageUrl) {
  const filename = filenameFromUrl(imageUrl);
  if (!filename) return null;
  const url = new URL(COMMONS_API);
  Object.entries({
    action: 'query', format: 'json', formatversion: '2', origin: '*',
    titles: `File:${filename}`, prop: 'imageinfo', iiprop: 'url', iiurlwidth: '640',
  }).forEach(([key, value]) => url.searchParams.set(key, value));
  const response = await fetch(url, { headers: { 'User-Agent': 'TinyOutingsImageRepair/1.0 (support@tinyoutings.app)' } });
  if (!response.ok) return null;
  const payload = await response.json();
  return payload?.query?.pages?.[0]?.imageinfo?.[0]?.thumburl || null;
}

const env = { ...process.env, ...parseEnv(await fs.readFile(path.join(ROOT, '.env.local'), 'utf8')) };
const activities = await getActivities(env);
const updates = [];
for (const [index, activity] of activities.entries()) {
  const resolvedUrl = await validThumbnailUrl(activity.wikimedia_image_url).catch(() => null);
  if (resolvedUrl && resolvedUrl !== activity.wikimedia_image_url) updates.push({ activity_id: activity.activity_id, wikimedia_image_url: resolvedUrl });
  if ((index + 1) % 25 === 0 || index + 1 === activities.length) console.log(`Checked ${index + 1}/${activities.length}; repaired ${updates.length}.`);
  await new Promise((resolve) => setTimeout(resolve, DELAY_MS));
}

const header = `-- Generated by scripts/repair-wikimedia-image-urls.js\n-- Valid Commons thumbnail URLs: ${updates.length} of ${activities.length} stored Wikimedia images.\n`;
const body = updates.length
  ? `with image_updates (activity_id, wikimedia_image_url) as (values\n  ${updates.map((item) => `(${sql(item.activity_id)}::uuid, ${sql(item.wikimedia_image_url)}::text)`).join(',\n  ')}\n)\nupdate public.activities as activity\nset wikimedia_image_url = image_updates.wikimedia_image_url, updated_at = now()\nfrom image_updates\nwhere activity.activity_id = image_updates.activity_id;\n`
  : '-- No URL repairs required.\n';
await fs.writeFile(OUTPUT_PATH, header + body);
console.log(`Wrote ${updates.length} repairs to ${path.relative(ROOT, OUTPUT_PATH)}.`);
