/* global process */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { happityListingExclusionReasons } from './lib/happity-listing-suitability.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputSql = join(root, 'supabase', 'seed', 'activity_happity_exclusion_archives.generated.sql');
const outputAudit = join(root, 'data', 'activity_happity_exclusion_archives.generated.json');

function readEnv() {
  const path = join(root, '.env.local');
  if (!existsSync(path)) return {};
  return Object.fromEntries(readFileSync(path, 'utf8').replace(/^\uFEFF/, '')
    .split(/\r?\n/)
    .filter((line) => line && !line.trim().startsWith('#') && line.includes('='))
    .map((line) => {
      const index = line.indexOf('=');
      return [line.slice(0, index).trim(), line.slice(index + 1).trim().replace(/^['"]|['"]$/g, '')];
    }));
}

function sql(value) {
  if (value === null || value === undefined) return 'null';
  return `$$${String(value).replaceAll('$$', '$ $')}$$`;
}

async function fetchHappityActivities(env) {
  const url = env.VITE_SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const key = env.VITE_SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY;
  if (!url || !key) throw new Error('VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY are required.');

  const rows = [];
  const select = 'activity_id,activity_name,description,source_name,data_source,source_url,website,public_listing_status,archive';
  for (let offset = 0; ; offset += 1000) {
    const params = new URLSearchParams({
      select,
      archive: 'not.is.true',
      or: '(source_name.eq.Happity,data_source.eq.Happity,source_url.ilike.*happity.co.uk*,website.ilike.*happity.co.uk*)',
      order: 'activity_id.asc',
      limit: '1000',
      offset: String(offset),
    });
    const response = await fetch(`${url}/rest/v1/activities?${params}`, {
      headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (!response.ok) throw new Error(`Could not load Happity activities: ${response.status}`);
    const page = await response.json();
    rows.push(...page);
    if (page.length < 1000) return rows;
  }
}

function buildSql(candidates) {
  if (!candidates.length) return '-- No explicitly religious or language-focused Happity activities found.\n';
  return `-- Generated by scripts/archive-happity-excluded-listings.js
-- Archive Happity listings whose activity content is explicitly religious or
-- language-focused. A church appearing only in a venue/address never matches.
with excluded_happity_listings (activity_id, archive_reason) as (
  values
    ${candidates.map((candidate) => `(${sql(candidate.activity_id)}::uuid, ${sql(candidate.reasons.join('; '))}::text)`).join(',\n    ')}
)
update public.activities as activity
set archive = true,
    public_listing_status = 'archived',
    archive_reason = excluded_happity_listings.archive_reason,
    archived_at = coalesce(activity.archived_at, now()),
    updated_at = now()
from excluded_happity_listings
where activity.activity_id = excluded_happity_listings.activity_id
  and coalesce(activity.archive, false) = false;
`;
}

async function main() {
  const records = await fetchHappityActivities(readEnv());
  const candidates = records
    .map((activity) => ({ ...activity, reasons: happityListingExclusionReasons(activity) }))
    .filter((activity) => activity.reasons.length)
    .sort((left, right) => left.activity_name.localeCompare(right.activity_name));

  const reasonCounts = candidates.reduce((counts, candidate) => {
    for (const reason of candidate.reasons) counts[reason] = (counts[reason] || 0) + 1;
    return counts;
  }, {});

  mkdirSync(dirname(outputSql), { recursive: true });
  mkdirSync(dirname(outputAudit), { recursive: true });
  writeFileSync(outputSql, buildSql(candidates));
  writeFileSync(outputAudit, JSON.stringify({
    generated_at: new Date().toISOString(),
    checked_happity_records: records.length,
    archived_candidates: candidates.length,
    reasons: reasonCounts,
    candidates: candidates.map(({ activity_id, activity_name, description, source_url, reasons }) => ({
      activity_id, activity_name, description, source_url, reasons,
    })),
  }, null, 2) + '\n');
  console.log(`Checked ${records.length} Happity listings; ${candidates.length} are explicitly religious or language-focused.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
